import java.lang.*;
public class EscapeSequence {
    public static void main(String args[]) {
        System.out.println("Hello \"Bhavana\"...");
        System.out.println("Hello \\Bhavana\\...");
        System.out.println("Hello \'Bhavana\'...");
        System.out.println("Hello \nBhavana...");
        System.out.println("Hello\tBhavana...");
        System.out.println("Hello\bBhavana...");
    }
}